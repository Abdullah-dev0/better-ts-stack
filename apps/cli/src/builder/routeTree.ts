// Writes TanStack Start's src/routeTree.gen.ts for the routes a project has.
// TanStack Router writes the same file on `vite dev` and `vite build`; writing
// it here lets the project type-check before either has run
import fs from "fs-extra";
import { readdir } from "node:fs/promises";
import path from "node:path";

import { buildError } from "../types";

export const ROUTE_TREE_FILE = "src/routeTree.gen.ts";

interface FileRoute {
  // "/", "/sign-in", "/api/auth/$"
  path: string;
  // "./routes/index", "./routes/api/auth/$"
  importPath: string;
  // "Index", "SignIn", "ApiAuthSplat"
  name: string;
}

// "api/auth/$" -> "ApiAuthSplat", "forgot-password" -> "ForgotPassword"
function routeName(file: string): string {
  return file
    .split(/[/-]/)
    .map((part) => (part === "$" ? "Splat" : part))
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

// shortcut: flat file routes only (no layout routes, route groups, or
// $param segments), which is all the templates use; extend it when one does
export function toFileRoutes(files: string[]): FileRoute[] {
  return files
    .map((file) => file.replace(/\.tsx?$/, ""))
    .filter((file) => file !== "__root")
    .map((file) => ({
      path: file === "index" ? "/" : `/${file}`,
      importPath: `./routes/${file}`,
      name: routeName(file),
    }))
    .sort((a, b) => {
      // The index route first, then by depth, then by name, as the generator
      const depth = (route: FileRoute) =>
        route.path === "/" ? 0 : route.path.split("/").length;
      return depth(a) - depth(b) || a.path.localeCompare(b.path);
    });
}

export function renderRouteTree(routes: FileRoute[]): string {
  const each = (line: (route: FileRoute) => string) =>
    routes.map(line).join("\n");
  // One line when it fits in 80 columns, as Prettier prints the generator's
  // output, otherwise one member per line
  const union = (key: string, values: string[]) => {
    const line = `  ${key}: ${values.join(" | ")}`;
    return line.length <= 80
      ? line
      : `  ${key}:\n${values.map((value) => `    | ${value}`).join("\n")}`;
  };
  const paths = routes.map((route) => `'${route.path}'`);

  return `/* eslint-disable */

// @ts-nocheck

// noinspection JSUnusedGlobalSymbols

// This file was automatically generated by TanStack Router.
// You should NOT make any changes in this file as it will be overwritten.
// Additionally, you should also exclude this file from your linter and/or formatter to prevent it from being checked or modified.

import { Route as rootRouteImport } from './routes/__root'
${each((r) => `import { Route as ${r.name}RouteImport } from '${r.importPath}'`)}

${each(
  (r) => `const ${r.name}Route = ${r.name}RouteImport.update({
  id: '${r.path}',
  path: '${r.path}',
  getParentRoute: () => rootRouteImport,
} as any)`
)}

export interface FileRoutesByFullPath {
${each((r) => `  '${r.path}': typeof ${r.name}Route`)}
}
export interface FileRoutesByTo {
${each((r) => `  '${r.path}': typeof ${r.name}Route`)}
}
export interface FileRoutesById {
  __root__: typeof rootRouteImport
${each((r) => `  '${r.path}': typeof ${r.name}Route`)}
}
export interface FileRouteTypes {
  fileRoutesByFullPath: FileRoutesByFullPath
${union("fullPaths", paths)}
  fileRoutesByTo: FileRoutesByTo
${union("to", paths)}
${union("id", ["'__root__'", ...paths])}
  fileRoutesById: FileRoutesById
}
export interface RootRouteChildren {
${each((r) => `  ${r.name}Route: typeof ${r.name}Route`)}
}

declare module '@tanstack/react-router' {
  interface FileRoutesByPath {
${each(
  (r) => `    '${r.path}': {
      id: '${r.path}'
      path: '${r.path}'
      fullPath: '${r.path}'
      preLoaderRoute: typeof ${r.name}RouteImport
      parentRoute: typeof rootRouteImport
    }`
)}
  }
}

const rootRouteChildren: RootRouteChildren = {
${each((r) => `  ${r.name}Route: ${r.name}Route,`)}
}
export const routeTree = rootRouteImport
  ._addFileChildren(rootRouteChildren)
  ._addFileTypes<FileRouteTypes>()

import type { getRouter } from './router.tsx'
import type { createStart } from '@tanstack/react-start'
declare module '@tanstack/react-start' {
  interface Register {
    ssr: true
    router: Awaited<ReturnType<typeof getRouter>>
  }
}
`;
}

export async function generateRouteTree(targetDir: string): Promise<void> {
  try {
    const routesDir = path.join(targetDir, "src/routes");
    const entries = await readdir(routesDir, {
      recursive: true,
      withFileTypes: true,
    });
    const files = entries
      .filter((entry) => entry.isFile() && /\.tsx?$/.test(entry.name))
      .map((entry) =>
        path
          .relative(routesDir, path.join(entry.parentPath, entry.name))
          .split(path.sep)
          .join("/")
      );
    await fs.writeFile(
      path.join(targetDir, ROUTE_TREE_FILE),
      renderRouteTree(toFileRoutes(files)),
      "utf-8"
    );
  } catch (error) {
    throw buildError(
      error,
      "ROUTE_TREE_ERROR",
      `Failed to write ${ROUTE_TREE_FILE}`
    );
  }
}
